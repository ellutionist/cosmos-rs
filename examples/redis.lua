-- Redis 端到端回归：每轮使用独立前缀，结束清理；写入的键同时配置过期时间。
local redis = require("cosmos.database.redis")
local url = (...) or os.getenv("COSMOS_REDIS_URL")
assert(url, "set COSMOS_REDIS_URL or pass a redis:// URL")
assert(redis == cosmos.database.redis and require("cosmos.database").redis == redis)
local opts = assert(redis.parse_url(url))
opts.timeout, opts.pool_size = 2000, 2
local prefix = "cosmos:test:" .. string.format("%.0f", cosmos.time.now_us()) .. ":" .. math.random(1000000) .. ":"
local keys, clients = {}, {}
local admin = redis.new()
assert(admin:connect(opts))
local acl_user
local function key(name) local value = prefix .. name; keys[value] = true; return value end
local function client(options)
    local value = assert(redis.client(options or opts)); clients[#clients+1] = value; return value
end
local function join(task) local _, err = task:join(); assert(err == nil, err) end
local function run()
    local pool = client()
    local conn = assert(pool:connect())
    assert(conn:ping() == "PONG" and conn:get_reused_times() == 0)
    local id = conn:client("ID")
    assert(type(id) == "number" or type(id) == "string")
    local payload = string.rep(string.char(0,128,255,13,10,1), 8192)
    assert(conn:set(key("value"), payload, "PX", 60000) == "OK")
    assert(conn:get(key("value")) == payload)
    assert(conn:set(key("empty"), "", "EX", 60) == "OK")
    local values = assert(conn:mget(key("missing"), key("value"), key("empty")))
    assert(#values == 3 and values[1] == cosmos.null and values[2] == payload and values[3] == "")
    assert(conn:set(key("integer"), "9223372036854775806", "EX", 60) == "OK")
    assert(conn:incr(key("integer")) == "9223372036854775807")
    local overflow, overflow_err = conn:incr(key("integer"))
    assert(overflow == false and overflow_err)
    assert(conn:set(key("integer"), "-9223372036854775807", "EX", 60) == "OK")
    assert(conn:decr(key("integer")) == "-9223372036854775808")
    assert(conn:hmset(key("hash"), {a="1", binary=payload}) == "OK")
    assert(conn:expire(key("hash"), 60) == 1)
    local fields = assert(conn:hmget(key("hash"), {"a", "missing", "binary"}))
    assert(fields[1] == "1" and fields[2] == cosmos.null and fields[3] == payload)
    assert(conn:array_to_hash(conn:hgetall(key("hash"))).binary == payload)
    local invalid, wrong_type = conn:get(key("hash"))
    assert(invalid == false and wrong_type:find("WRONGTYPE", 1, true))
    assert(conn:command("COUNT") > 0, "generic execution must not override the native COMMAND command")
    assert(conn:hello(3) == nil)
    assert(conn:monitor() == nil)
    assert(conn:ping() == "PONG")

    assert(conn:init_pipeline())
    conn:set(key("pipeline"), "batch", "EX", 60)
    conn:get(key("pipeline"))
    conn:get(key("missing"))
    conn:get(key("hash"))
    conn:ping()
    assert(conn:set_keepalive() == nil)
    local replies = assert(conn:commit_pipeline())
    assert(#replies == 5 and replies[1] == "OK" and replies[2] == "batch" and replies[3] == cosmos.null)
    assert(replies[4][1] == false and replies[4][2]:find("WRONGTYPE", 1, true) and replies[5] == "PONG")
    assert(conn:init_pipeline())
    conn:set(key("cancelled_pipeline"), "unused", "EX", 60)
    assert(conn:cancel_pipeline())
    assert(conn:get(key("cancelled_pipeline")) == cosmos.null)
    assert(conn:init_pipeline())
    assert(#conn:commit_pipeline() == 0)

    assert(conn:multi() == "OK")
    assert(conn:set(key("transaction"), "committed", "EX", 60) == "QUEUED")
    assert(conn:set_keepalive() == nil)
    assert(conn:exec()[1] == "OK")
    assert(conn:multi() == "OK")
    assert(conn:set(key("transaction"), "discarded", "EX", 60) == "QUEUED")
    assert(conn:discard() == "OK")
    assert(conn:get(key("transaction")) == "committed")
    assert(conn:watch(key("watched")) == "OK")
    assert(conn:set_keepalive() == nil)
    assert(admin:set(key("watched"), "changed", "EX", 60) == "OK")
    assert(conn:multi() == "OK")
    assert(conn:set(key("transaction"), "aborted", "EX", 60) == "QUEUED")
    assert(conn:exec() == cosmos.null)
    assert(conn:get(key("transaction")) == "committed")
    assert(conn:init_pipeline())
    conn:multi(); conn:set(key("transaction"), "pipeline", "EX", 60); conn:get(key("transaction")); conn:exec()
    local transaction = assert(conn:commit_pipeline())
    assert(transaction[1] == "OK" and transaction[2] == "QUEUED" and transaction[3] == "QUEUED")
    assert(transaction[4][1] == "OK" and transaction[4][2] == "pipeline")
    assert(conn:multi() == "OK")
    assert(conn:set(key("transaction")) == false)
    local aborted, abort_err = conn:exec()
    assert(aborted == false and abort_err:find("EXECABORT", 1, true))
    assert(conn:set_keepalive())
    assert(conn:get(key("value")) == nil, "returned handles must be invalidated")
    conn = assert(pool:connect())
    assert(conn:get_reused_times() == 1 and conn:client("ID") == id)
    assert(conn:set_keepalive())
    local separate = assert(client():connect())
    assert(separate:client("ID") ~= id)
    assert(separate:close())

    local stale = assert(pool:connect())
    local stale_id = stale:client("ID")
    assert(pool:release(stale))
    assert(admin:client("KILL", "ID", stale_id) == 1)
    local recovered = assert(pool:connect())
    assert(recovered:get_reused_times() == 0 and recovered:client("ID") ~= stale_id)
    assert(pool:release(recovered))

    local subscriber = assert(pool:connect())
    local channel = prefix .. "channel:one"
    local subscribed = assert(subscriber:subscribe(channel, channel))
    assert(#subscribed == 2 and subscribed[1][1] == "subscribe")
    assert(subscriber:psubscribe(prefix .. "channel:*")[1] == "psubscribe")
    assert(subscriber:set_keepalive() == nil)
    assert(admin:publish(channel, payload) == 2)
    local pong = assert(subscriber:ping())
    assert(pong[1] == "pong")
    local a, b = assert(subscriber:read_reply()), assert(subscriber:read_reply())
    assert(a[#a] == payload and b[#b] == payload and a[1] ~= b[1])
    local unsubscribed = assert(subscriber:unsubscribe(prefix .. "absent", channel))
    assert(#unsubscribed == 2 and unsubscribed[2][1] == "unsubscribe")
    assert(subscriber:punsubscribe()[1] == "punsubscribe")
    assert(subscriber:ping() == "PONG")
    assert(subscriber:set_keepalive())

    local reset = assert(pool:connect())
    assert(reset:subscribe(channel))
    assert(reset:reset() == "RESET")
    local message, message_err = reset:read_reply()
    assert(message == nil and message_err == "not subscribed")
    assert(reset:ping() == "PONG")
    assert(pool:release(reset) == nil)
    assert(reset:close())

    local timed = assert(pool:connect())
    assert(timed:set_timeouts(2000,2000,10))
    local _, timeout = timed:blpop(key("blocking"), 0)
    assert(timeout and timeout:find("timeout",1,true))
    assert(pool:release(timed) == nil)
    local cancelled = assert(pool:connect())
    local started = false
    local task = cosmos.thread.spawn(function() started=true; cancelled:blpop(key("blocking"),0) end)
    while not started do cosmos.time.sleep(0) end
    cosmos.time.sleep(10); task:kill()
    local _, cancellation = task:join()
    assert(cancellation and cancellation:find("cancelled",1,true))
    assert(pool:release(cancelled) == nil)
    assert(cancelled:close())
    local changed = assert(pool:connect())
    assert(changed:select(opts.db) == "OK")
    assert(pool:release(changed) == nil, "connections with modified session state must not return to the pool")
    assert(changed:close())
    local tasks = {}
    for i=1,4 do
        tasks[i] = cosmos.thread.spawn(function()
            local value = assert(pool:connect())
            assert(value:set(key("parallel"..i), "value", "EX", 60) == "OK")
            assert(value:get(key("parallel"..i)) == "value")
            assert(pool:release(value))
        end)
    end
    for _, pending in ipairs(tasks) do join(pending) end

    -- 临时 ACL 用户仅用于本轮认证验证，结束时删除，不更改现有用户。
    acl_user = "cosmos-test-" .. prefix:gsub(":", "-")
    local password = "test-" .. string.format("%.0f", cosmos.time.now_us())
    assert(admin:acl("SETUSER", acl_user, "reset", "on", ">"..password, "~"..prefix.."*", "&"..prefix.."*", "+@all") == "OK")
    local authenticated = {}
    for name, value in pairs(opts) do authenticated[name] = value end
    authenticated.username, authenticated.password = acl_user, password
    authenticated.db = opts.db == 0 and 1 or 0
    local auth_client = client(authenticated)
    local authed = assert(auth_client:connect())
    assert(authed:ping() == "PONG")
    assert(authed:set(key("value"), "other database", "EX", 60) == "OK")
    assert(admin:get(key("value")) == payload)
    assert(authed:del(key("value")) == 1)
    assert(auth_client:release(authed))
    authed = assert(auth_client:connect())
    assert(authed:get_reused_times() == 1 and authed:ping() == "PONG")
    assert(auth_client:release(authed))
    auth_client:close()
    authenticated.password = password .. "invalid"
    local rejected = redis.new()
    local login, auth_error = rejected:connect(authenticated)
    assert(login == nil and auth_error:find("authenticate",1,true))
    rejected:close()
    pool:close()
    assert(pool:connect() == nil)
end
local success, failure = xpcall(run, debug.traceback)
for _, pool in ipairs(clients) do pool:close() end
local cleanup_errors = {}
for name in pairs(keys) do
    local cleaned, err = admin:del(name)
    if not cleaned then cleanup_errors[#cleanup_errors+1] = tostring(err) end
end
if acl_user then
    local cleaned, err = admin:acl("DELUSER", acl_user)
    if not cleaned then cleanup_errors[#cleanup_errors+1] = tostring(err) end
end
admin:close()
assert(success, failure)
assert(#cleanup_errors == 0, table.concat(cleanup_errors, "; "))
print("Redis binary data, NULL, integers, pipelines, transactions, Pub/Sub, pools, ACL, timeouts and cancellation passed")
