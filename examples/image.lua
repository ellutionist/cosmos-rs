-- PNG/JPEG/WebP 与通用像素操作；传入临时父目录可验证 FS 原子发布。
local parent=...
local Image=require('cosmos.image')
assert(Image==cosmos.image)
package.loaded['cosmos.image']=nil
assert(require('cosmos.image')==Image)
local function pixel(image,x,y,r,g,b,a)
    local c=assert(image:pixel(x,y));assert(c.r==r and c.g==g and c.b==b and c.a==a,'pixel mismatch')
end
local bytes=string.char(255,0,0,255, 0,255,0,128, 0,0,255,0, 255,255,255,255)
local original=assert(Image.from_pixels(2,2,'rgba8',bytes))
assert(original:width()==2 and original:height()==2)
local info=original:info();assert(info.width==2 and info.height==2 and info.pixel_format=='rgba8' and info.bytes==16)
pixel(original,1,0,0,255,0,128)
assert(original:pixels()==bytes)
assert(original:pixels('rgb8')==string.char(255,0,0, 0,255,0, 0,0,255, 255,255,255))
local gray=assert(original:pixels('luma8'));assert(#gray==4 and gray:byte(4)==255)
local mask=assert(Image.from_pixels(2,2,'luma8',string.char(0,64,128,255)))
pixel(mask,1,0,64,64,64,255)
local rgb=assert(Image.from_pixels(1,1,'rgb8',string.char(5,6,7)));pixel(rgb,0,0,5,6,7,255)
local empty=assert(Image.new(1,1));pixel(empty,0,0,0,0,0,0)
local patched=assert(original:with_pixels(1,0,1,2,'rgb8',string.char(1,2,3,4,5,6)))
pixel(patched,1,0,1,2,3,255);pixel(patched,1,1,4,5,6,255)
pixel(original,1,0,0,255,0,128)

local encoded={}
for _,format in ipairs({'png','webp'}) do
    encoded[format]=assert(original:encode(format))
    local decoded=assert(Image.decode(encoded[format]))
    assert(decoded:pixels()==bytes,format..' lossless round-trip failed')
    assert(Image.decode(encoded[format],{max_pixels=3})==nil)
    assert(Image.decode(encoded[format],{max_width=1})==nil)
    assert(Image.decode(encoded[format],{max_height=1})==nil)
    assert(Image.decode(encoded[format],{max_pixels=0})==nil)
    assert(original:encode(format,{quality=90})==nil)
end
-- JPEG 使用单色大块验证有损误差；透明合成由编码参数显式选择。
local solid=assert(Image.new(64,32,{r=80,g=140,b=200}))
local jpeg=assert(solid:encode('jpeg',{quality=95}))
local decoded=assert(Image.decode(jpeg))
assert(decoded:width()==64 and decoded:height()==32)
local c=decoded:pixel(20,10)
assert(math.abs(c.r-80)<=3 and math.abs(c.g-140)<=3 and math.abs(c.b-200)<=3)
local transparent=assert(Image.new(32,32,{r=255,g=0,b=0,a=0}))
local white=assert(Image.decode(assert(transparent:encode('jpeg',{quality=100,background={r=255,g=255,b=255}}))))
c=white:pixel(0,0);assert(c.r>=253 and c.g>=253 and c.b>=253 and c.a==255)
local dropped=assert(Image.decode(assert(transparent:encode('jpeg',{quality=100}))))
c=dropped:pixel(0,0);assert(c.r>=250 and c.g<=3 and c.b<=3)
assert(original:encode('jpeg',{quality=1.5})==nil and original:encode('jpeg',{quality=101})==nil)
assert(original:encode('jpeg',{background={a=128}})==nil)
print('Image pixels, PNG/WebP lossless and JPEG quality/background passed')

local crop=assert(original:crop(1,0,1,2));pixel(crop,0,0,0,255,0,128)
local big=assert(original:resize(4,4,'nearest'))
pixel(big,0,0,255,0,0,255);pixel(big,3,3,255,255,255,255)
for _,filter in ipairs({'triangle','catmull_rom','gaussian','lanczos3'}) do
    local resized=assert(solid:resize(16,8,filter));assert(resized:width()==16 and resized:height()==8)
end
local thumb=assert(solid:thumbnail(20,20));assert(thumb:width()==20 and thumb:height()==10)
assert(solid:thumbnail(128,128):width()==64)
assert(solid:thumbnail(128,128,true):width()==128)
assert(solid:thumbnail(16000,16000):width()==64)
pixel(assert(original:rotate(90)),0,0,0,0,255,0)
pixel(assert(original:rotate(180)),0,0,255,255,255,255)
pixel(assert(original:rotate(270)),0,0,0,255,0,128)
pixel(assert(original:flip('horizontal')),0,0,0,255,0,128)
pixel(assert(original:flip('vertical')),0,0,0,0,255,0)
assert(solid:rotate(90):width()==32 and solid:rotate(90):height()==64)
-- 应用可自行组合比例裁剪、固定宽度重采样及灰度像素来实现封面与检测策略。
local cover=assert(Image.new(900,600,{r=100,g=120,b=140}))
local poster=assert(cover:crop(500,0,400,600))
assert(poster:width()==400 and poster:height()==600)
local plane=assert(cover:resize(800,533,'triangle')):pixels('luma8')
assert(#plane==800*533)
print('Image crop, filters, thumbnail, rotation and pixel-plane processing passed')

local a=cosmos.thread.spawn(function() return assert(cover:resize(300,200,'triangle')) end)
local b=cosmos.thread.spawn(function() return assert(cover:encode('png')) end)
assert(a:join()==nil and b:join()==nil)
assert(cover:width()==900 and cover:height()==600)
for _,size in ipairs({0,-1,1.5,16001,math.huge}) do assert(Image.new(size,1)==nil) end
assert(Image.new(16000,16000)==nil)
assert(Image.new(1,1,{r=256})==nil and Image.new(1,1,{a=-1})==nil)
assert(Image.from_pixels(2,2,'rgba8','short')==nil)
assert(Image.from_pixels(1,1,'unknown','abc')==nil)
assert(Image.decode('not an image')==nil and Image.decode(encoded.png:sub(1,20))==nil)
assert(original:encode('gif')==nil and original:pixels('rgb16')==nil)
assert(original:crop(1,1,2,2)==nil and original:crop(-1,0,1,1)==nil)
assert(original:pixel(2,0)==nil and original:pixel(0,0.5)==nil)
assert(original:resize(2,2,'unknown')==nil)
assert(original:rotate(45)==nil and original:flip('diagonal')==nil)
assert(original:with_pixels(0,0,1,1,'rgb8','bad size')==nil)
-- 输入和输出都不大、但纵向浮点中间缓冲过大的长宽比交叉必须预先拒绝。
local strip=assert(Image.new(16000,1))
local failed,why=strip:resize(1,16000,'triangle')
assert(failed==nil and why:find('working memory',1,true),why)
assert(strip:width()==16000 and strip:height()==1)
assert(Image.decode(encoded.png):pixels()==bytes)
print('Image bounds, memory guards, concurrency and recovery passed')

if parent then
    local path=assert(cosmos.fs.path.join(parent,'cosmos-image-'..string.format('%.0f',cosmos.time.now_us())..'.png'))
    assert(cosmos.fs.write_atomic(path,encoded.png,{no_replace=true}))
    assert(Image.decode(assert(cosmos.fs.read_file(path))):pixels()==bytes)
    assert(cosmos.fs.remove_file(path))
    print('Image atomic filesystem round-trip passed')
end
