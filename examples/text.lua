-- 需要 CLI text feature，或由宿主注入 cosmos_text::Text。
local regex = require('cosmos.text.regex')
local unicode = require('cosmos.text.unicode')
local chinese = require('cosmos.text.chinese')
assert(require('cosmos.text') == cosmos.text)
assert(cosmos.text.regex == regex and cosmos.text.unicode == unicode and cosmos.text.chinese == chinese)
assert(regex.match == require('cosmos.text.regex.match'))
assert(regex.matches == require('cosmos.text.regex.matches'))

-- 编译后复用；位置沿用 Lua string.sub 的一基、闭区间字节约定。
local pattern = assert(regex.new('(?P<word>[a-z]+)(?:-(?P<number>[0-9]+))?', {case_insensitive=true}))
assert(pattern:pattern() == '(?P<word>[a-z]+)(?:-(?P<number>[0-9]+))?')
assert(pattern:is_match('ALPHA-12 beta'))
local names = pattern:capture_names()
assert(#names == 3 and names[1].index == 0 and names[1].name == nil and names[2].name == 'word')
local matches = assert(pattern:find_all('ALPHA-12 beta'))
assert(matches:len() == 2)
local first = assert(matches:next())
assert(first:text() == 'ALPHA-12' and first:group('word') == 'ALPHA' and first:group(2) == '12')
local a, b = first:range('word')
assert(a == 1 and b == 5 and ('ALPHA-12 beta'):sub(a,b) == first:group('word'))
assert(first:capture_count() == 2 and matches:get(2):group('number') == nil)
assert(matches:next():text() == 'beta' and matches:next() == nil and matches:get(3) == nil)
local replaced, count = assert(pattern:replace('ALPHA-12 beta', '${word}:$number:$$'))
assert(replaced == 'ALPHA:12:$ beta::$' and count == 2)
replaced, count = assert(pattern:replace('alpha-12 beta gamma-34', function(m)
    cosmos.time.sleep(1) -- 回调可以挂起；返回 nil/false 保留原匹配。
    if m:group('number') then return m:group('word') end
    return false
end))
assert(replaced == 'alpha beta gamma' and count == 2)
assert(pattern:find('123') == nil)
local parts = assert(regex.new('[,;]')):split('a,b;c,d', 3)
assert(#parts == 3 and parts[1] == 'a' and parts[3] == 'c,d')
local literal = 'a.b[1]+(x)?$^|{}\\'
assert(assert(regex.new('^' .. assert(regex.escape(literal)) .. '$')):is_match(literal))
local limited = assert(pattern:find_all('one two three', 2))
assert(limited:len() == 2)
local once, n = assert(pattern:replace('one two three', 'x', 1))
assert(once == 'x two three' and n == 1)

-- UTF-8 文本；字符计数/截断以 Unicode scalar 为单位，不等于字节或字形簇。
local e_acute, decomposed = '\195\169', 'e\204\129'
assert(unicode.normalize(decomposed, 'nfc') == e_acute)
assert(unicode.normalize(e_acute, 'nfd') == decomposed)
assert(unicode.normalize('\239\188\161\239\188\162\239\188\163\239\188\145\239\188\146', 'nfkc') == 'ABC12')
assert(unicode.normalize('\239\172\131', 'nfkd') == 'ffi')
assert(unicode.upper('stra\195\159e') == 'STRASSE')
assert(unicode.lower('\206\159\206\163') == '\206\191\207\130')
assert(unicode.trim('\227\128\128 a\194\160') == 'a')
assert(unicode.len(decomposed) == 2 and unicode.len(e_acute) == 1)
assert(unicode.truncate(e_acute .. 'ab', 2) == e_acute .. 'a')
assert(unicode.truncate('abc', 0) == '')
local m = assert(assert(regex.new('(?P<x>.)')):find(e_acute .. 'x', 3))
assert(m:text() == 'x' and m:range() == 3)
local empty = assert(assert(regex.new('')):find(e_acute, 3))
local start, finish = empty:range()
assert(start == 3 and finish == 2 and empty:text() == '')
assert(assert(regex.new('')):find_all(e_acute):len() == 2)
assert(unicode.len('a\0b') == 3)

-- 固定 OpenCC 内嵌词典，与原生 Rust 后端使用相同配置。
local traditional = '\231\185\129\233\171\148\228\184\173\230\150\135'
local simplified = '\231\185\129\228\189\147\228\184\173\230\150\135'
assert(chinese.convert(traditional, 't2s') == simplified)
assert(chinese.convert(simplified, 's2t') == traditional)
assert(chinese.convert('a\0b', 't2s') == 'a\0b')

local function fails(value, err, expected)
    assert(value == nil and type(err) == 'string' and (not expected or err:find(expected, 1, true)), tostring(err))
end
fails(regex.new('['))
fails(regex.new('(?=a)'))
fails(pattern:find(e_acute, 2))
fails(pattern:find('x', 0))
fails(pattern:find_all('x', 1.5))
fails(first:group('missing'))
fails(first:group(-1))
fails(pattern:replace('x', function() return nil, 'callback failed' end))
fails(pattern:replace('x', function() error('callback error') end))
fails(pattern:replace('x', function() return true end))
fails(pattern:replace('x', function() return '\255' end))
fails(pattern:replace('x', '\255'))
fails(pattern:is_match('\255'))
fails(unicode.normalize('x', 'invalid'))
fails(unicode.normalize('\255', 'nfc'))
fails(unicode.truncate('x', -1))
fails(chinese.convert('x', 'unknown'))
fails(chinese.convert('\255', 't2s'))
assert(unicode.upper('ready') == 'READY' and pattern:is_match('ready'))
print('text ok')
