-- 需要 database feature 和显式测试服务器；临时对象在退出前删除。
local mysql_url,redis_url=...
assert(mysql_url and redis_url,'pass MySQL and Redis test URLs')
local Mysql,Redis=cosmos.database.mysql,cosmos.database.redis
local nonce=cosmos.encoding.hex.encode(assert(cosmos.encryption.random.bytes(6)))
local name='cosmos_resource_'..nonce
local key='cosmos:resource:'..nonce
local mysql_options=assert(Mysql.parse_url(mysql_url))
local redis_options=assert(Redis.parse_url(redis_url))
for _,options in ipairs({mysql_options,redis_options}) do options.max_connections=1;options.max_waiters=1;options.acquire_timeout=30 end
local mysql=assert(Mysql.client(mysql_options))
local redis=assert(Redis.client(redis_options))
local ok,reason=pcall(function()
    local conn=assert(mysql:connect())
    assert(conn:query('CREATE TABLE '..name..' (id BIGINT PRIMARY KEY, value VARBINARY(500))'))
    assert(conn:query('CREATE PROCEDURE '..name..'_p() BEGIN SELECT 1 AS a; SELECT 2 AS b; END'))
    local call=assert(conn:prepare('CALL '..name..'_p()'))
    local first,again=call:execute();assert(tonumber(first[1].a)==1 and again=='again')
    local second,again=conn:read_result();assert(tonumber(second[1].b)==2 and again=='again')
    assert(conn:read_result());assert(call:close())
    local insert=assert(conn:prepare('INSERT INTO '..name..' (id,value) VALUES (?,?)'))
    assert(insert:param_count()==2)
    assert(insert:execute({1,'binary\0\255'}).affected_rows==1)
    assert(insert:execute({2,cosmos.null}).affected_rows==1)
    assert(insert:execute({1})==nil and insert:execute({3,0/0})==nil)
    assert(insert:close())
    assert(insert:execute({3,'closed'})==nil)
    local limited=assert(conn:prepare('SELECT ? AS n LIMIT ?'));assert(limited:execute({42,1})[1].n=='42');assert(limited:close())
    local select=assert(conn:prepare('SELECT id,value, CAST(18446744073709551615 AS UNSIGNED) AS precise, CAST(1.234567890123456789 AS DECIMAL(20,18)) AS decimal_value FROM '..name..' WHERE id=?'))
    local rows=assert(select:execute({1}))
    assert(rows[1].id=='1' and rows[1].value=='binary\0\255')
    assert(rows[1].precise=='18446744073709551615' and rows[1].decimal_value=='1.234567890123456789')
    assert(select:close())
    local types=assert(conn:prepare('SELECT ? AS b,? AS n,? AS s,? AS z,CAST(? AS DATE) AS d,CAST(? AS DATETIME(6)) AS t,CAST(? AS TIME(6)) AS duration'))
    local row=assert(types:execute({true,1.25,string.rep('x',300),cosmos.null,'2024-02-29','2024-02-29 12:34:56.123456','-25:02:03.000004'}))[1]
    assert(tonumber(row.b)==1 and row.n==1.25 and #row.s==300 and row.z==cosmos.null)
    assert(row.d=='2024-02-29' and row.t=='2024-02-29 12:34:56.123456' and row.duration=='-25:02:03.000004')
    assert(mysql:stats().in_use==1)
    local waiter=cosmos.thread.spawn(function() local c,e=mysql:connect();assert(c==nil and e:find('acquire',1,true)) end)
    cosmos.time.sleep(2);assert(mysql:stats().waiting==1)
    local blocked,err=mysql:connect();assert(blocked==nil and err=='connection wait queue is full')
    waiter:join();assert(mysql:stats().waiting==0)
    assert(mysql:release(conn))
    assert(types:execute({true,1,'x',cosmos.null,'2024-01-01','2024-01-01 00:00:00','0:00:00'})==nil)
    assert(mysql:stats().in_use==0 and mysql:stats().idle==1)
    assert(mysql:transaction(function(c)
        assert(c:query('INSERT INTO '..name..' VALUES (3, '..Mysql.quote_sql_str('committed')..')'))
        cosmos.time.sleep(1);return 'committed'
    end)=='committed')
    local failed,error_message=mysql:transaction(function(c)
        assert(c:query('INSERT INTO '..name..' VALUES (4, '..Mysql.quote_sql_str('rolled back')..')'))
        error('rollback requested')
    end)
    assert(failed==nil and error_message:find('rollback requested',1,true))
    local count,count_error=mysql:with_connection(function(c)return assert(c:query('SELECT COUNT(*) AS n FROM '..name))[1].n end)
    assert(tonumber(count)==3,'unexpected committed row count: '..tostring(count)..' '..tostring(count_error))
    assert(mysql:stats().in_use==0)
    local values=assert(redis:transaction(function(c)
        assert(c:set(key,'transaction','EX',60)=='QUEUED');assert(c:get(key)=='QUEUED')
    end))
    assert(values[1]=='OK' and values[2]=='transaction')
    local failed,err=redis:transaction(function(c) assert(c:set(key,'rolled back','EX',60)=='QUEUED');return nil,'abort requested' end)
    assert(failed==nil and err=='abort requested')
    assert(redis:with_connection(function(c)return c:get(key) end)=='transaction')
    assert(redis:stats().in_use==0)
    local entered=cosmos.sync.channel.new(1)
    local task=cosmos.thread.spawn(function()
        redis:with_connection(function(c) entered:send(true);c:blpop(key..':missing',60) end)
    end)
    assert(entered:recv());cosmos.time.sleep(2);task:kill();task:join()
    collectgarbage('collect');collectgarbage('collect');cosmos.time.sleep(1)
    assert(redis:stats().in_use==0,'cancelled scope retained its lease after GC')
    local held=assert(redis:connect())
    local waiting=cosmos.thread.spawn(function() local c,e=redis:connect();assert(c==nil and e=='client is closed') end)
    cosmos.time.sleep(2);redis:close();waiting:join();held:close()
    assert(redis:stats().in_use==0)
end)
-- 使用独立连接清理，作用域失败也不会将测试对象遗留到正常返回路径。
local cleanup=assert(Mysql.new());assert(cleanup:connect(mysql_url));cleanup:query('DROP PROCEDURE IF EXISTS '..name..'_p');cleanup:query('DROP TABLE IF EXISTS '..name);cleanup:close()
local cleanup=assert(Redis.new());assert(cleanup:connect(redis_url));cleanup:del(key);cleanup:close()
mysql:close();redis:close()
assert(ok,reason)
print('Prepared bindings, binary rows, pool budgets, queue timeouts and transaction scopes passed')
