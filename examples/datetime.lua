-- builtin 日期、IANA 时区与单调计时，不需要插件。
local time = require('cosmos.time')
local datetime = require('cosmos.time.datetime')
local Instant = require('cosmos.time.instant')
local Deadline = require('cosmos.time.deadline')
assert(datetime == time.datetime and Instant == time.instant and Deadline == time.deadline)
local original = assert(datetime.parse('2024-02-29T12:34:56.789+08:00'))
assert(original:to_rfc3339() == '2024-02-29T12:34:56.789+08:00')
local utc = assert(original:with_timezone('UTC'))
assert(utc:format('%Y-%m-%d %H:%M:%S') == '2024-02-29 04:34:56')
assert(utc:timestamp_ms() == original:timestamp_ms())
assert(datetime.from_timestamp_ms(original:timestamp_ms(), '+08:00'):to_rfc3339() == original:to_rfc3339())
local parts = original:parts()
assert(parts.year == 2024 and parts.month == 2 and parts.day == 29 and parts.weekday == 4)
assert(parts.ordinal == 60 and parts.offset_seconds == 28800 and parts.millisecond == 789)
assert(datetime.new({year=2024, month=2, day=29, hour=12, minute=34, second=56,
    millisecond=789, timezone='Asia/Shanghai'}):timestamp_ms() == original:timestamp_ms())
assert(datetime.parse('2024/02/29 12:34', '%Y/%m/%d %H:%M', 'Asia/Shanghai'):parts().hour == 12)
assert(datetime.parse('2024-02-29', '%Y-%m-%d'):parts().hour == 0)
assert(datetime.parse('2024-02-29+08:00', '%Y-%m-%d%:z'):to_rfc3339() == '2024-02-29T00:00:00+08:00')
assert(datetime.parse('2024-02-29 12', '%Y-%m-%d %H') == nil)
assert(datetime.parse('0', '%s', 'Asia/Shanghai'):timestamp_ms() == 0)
assert(datetime.parse('2024-02-29 12:34:56.123456789', '%Y-%m-%d %H:%M:%S%.f'):format('%Y-%m-%d %H:%M:%S%.f') == '2024-02-29 12:34:56.123456789')
assert(datetime.parse('2024-02-29T12:34:56.123456789', '%Y-%m-%dT%H:%M:%S%.f'):parts().nanosecond == 123456789)
assert(datetime.from_timestamp_ms(-1):to_rfc3339() == '1969-12-31T23:59:59.999Z')
local precise = assert(datetime.from_timestamp_ns('1709164800123456789'))
assert(precise:timestamp_ns() == '1709164800123456789')
assert(precise:parts().nanosecond == 123456789)
assert(datetime.parse(precise:to_rfc3339()):timestamp_ns() == precise:timestamp_ns())
assert(datetime.from_timestamp_ns('-1'):to_rfc3339() == '1969-12-31T23:59:59.999999999Z')
assert(datetime.from_timestamp_ns('-1'):timestamp_ns() == '-1')
assert(datetime.from_timestamp_ns('1e9') == nil and datetime.from_timestamp_ns('') == nil)
assert(datetime.from_timestamp_ns(string.rep('9',41)) == nil)
assert(datetime.parse('9999-12-31T23:59:59.999999999Z'):timestamp_ns() == '253402300799999999999')
assert(datetime.from_timestamp_ns('253402300799999999999'):parts().year == 9999)
assert(original:add_ms(1500):diff_ms(original) == 1500)
assert(original:diff_ms(original:add_ms(1500)) == -1500)

-- DST 缺口和重叠明确拒绝，显式偏移能消除歧义。
local missing, err = datetime.parse('2024-03-10 02:30:00', '%Y-%m-%d %H:%M:%S', 'America/New_York')
assert(missing == nil and err:find('nonexistent', 1, true))
local ambiguous; ambiguous, err = datetime.parse('2024-11-03 01:30:00', '%Y-%m-%d %H:%M:%S', 'America/New_York')
assert(ambiguous == nil and err:find('ambiguous', 1, true))
local summer = assert(datetime.parse('2024-11-03T01:30:00-04:00', nil, 'America/New_York'))
local winter = assert(datetime.parse('2024-11-03T01:30:00-05:00', nil, 'America/New_York'))
assert(winter:diff_ms(summer) == 3600000)
assert(summer:format('%Z') == 'EDT' and winter:format('%Z') == 'EST')
assert(datetime.parse('2023-02-29T00:00:00Z') == nil)
assert(datetime.new({year=2024, month=4, day=31}) == nil)
assert(datetime.new({year=2024, month=2.5, day=1}) == nil)
assert(datetime.parse('2016-12-31T23:59:60Z') == nil)
assert(datetime.parse('0000-01-01T00:00:00Z') == nil)
assert(datetime.from_timestamp_ms(9007199254740991) == nil)
assert(datetime.from_timestamp_ms(1.5) == nil)
assert(original:with_timezone('Mars/Olympus') == nil)
assert(original:with_timezone('+24:00') == nil)
assert(original:with_timezone('+08:99') == nil)
assert(original:with_timezone('+08:00:00') == nil)
assert(original:format('%Q') == nil)
assert(datetime.parse(string.rep('x',4097)) == nil)
local edge = assert(datetime.parse('9999-12-31T23:59:59.999Z'))
assert(edge:with_timezone('+01:00') == nil and edge:add_ms(1) == nil)
assert(datetime.parse('0001-01-01T00:00:00Z'):with_timezone('-01:00') == nil)
assert(original:format('%Y') == '2024')

-- now 仍为真实时间，Instant / Deadline 独立测量经过时间。
local before, after = time.now_ms(), datetime.now('Asia/Shanghai'):timestamp_ms()
assert(after >= before and after <= time.now_ms())
local first = Instant.now()
local deadline = first:deadline(15)
assert(deadline:remaining_ms() >= 0)
deadline:wait()
assert(deadline:expired() and deadline:remaining_ms() == 0)
local second = Instant.now()
assert(first:elapsed_ms() >= 14 and second:duration_since(first) >= 14)
assert(first:duration_since(second) == nil)
local immediate = Deadline.after(0)
assert(immediate:expired())
immediate:wait()
assert(not pcall(Deadline.after, -1))
assert(not pcall(Deadline.after, math.huge))
assert(not pcall(Deadline.after, '1'))
print('Datetime, timezone, DST, validation and monotonic clocks passed')

-- 日历运算保留当地时间；月末默认截断，也可显式拒绝。
local jan = assert(datetime.parse('2024-01-31T12:34:56.123456789+08:00'))
assert(jan:add_calendar({months=1}):to_rfc3339() == '2024-02-29T12:34:56.123456789+08:00')
assert(jan:add_calendar({months=1,overflow='reject'}) == nil)
assert(jan:add_calendar({months=-1}):parts().year == 2023)
assert(jan:add_calendar({months=1}):add_calendar({years=1}):parts().day == 28)
assert(jan:add_calendar({years=1,months=-12}):timestamp_ns() == jan:timestamp_ns())
assert(jan:add_calendar({weeks=1,days=-7}):timestamp_ns() == jan:timestamp_ns())
assert(jan:parts().days_in_month == 31 and jan:add_calendar({months=1}):parts().days_in_month == 29)
local dst = assert(datetime.parse('2024-03-09T12:00:00-05:00', nil, 'America/New_York'))
assert(dst:add_calendar({days=1}):parts().hour == 12 and dst:add_ms(86400000):parts().hour == 13)
assert(dst:add_calendar({days=1}):diff_ms(dst) == 23*3600000)
local missing = assert(datetime.parse('2024-03-09T02:30:00-05:00',nil,'America/New_York'))
assert(missing:add_calendar({days=1}) == nil)
local fold = assert(datetime.parse('2024-11-02T01:30:00-04:00',nil,'America/New_York'))
assert(fold:add_calendar({days=1}) == nil)
local early = assert(fold:add_calendar({days=1,ambiguity='earliest'}))
local late = assert(fold:add_calendar({days=1,ambiguity='latest'}))
assert(late:diff_ms(early) == 3600000 and early:parts().hour == 1 and late:parts().hour == 1)
assert(jan:start_of('day'):format('%Y-%m-%d %H:%M:%S') == '2024-01-31 00:00:00')
assert(jan:start_of('week'):format('%Y-%m-%d') == '2024-01-29')
assert(jan:start_of('month'):format('%Y-%m-%d') == '2024-01-01')
assert(jan:start_of('year'):parts().ordinal == 1)
assert(datetime.parse('2021-01-01T00:00:00Z'):parts().iso_year == 2020)
assert(datetime.parse('2021-01-01T00:00:00Z'):parts().iso_week == 53)
local maildate = assert(datetime.parse_rfc2822('Tue, 1 Jul 2003 10:52:37 +0200'))
assert(maildate:to_rfc2822() == 'Tue, 1 Jul 2003 10:52:37 +0200')
assert(maildate:with_timezone('UTC'):format('%H:%M:%S') == '08:52:37')
assert(datetime.parse_rfc2822('invalid') == nil)
assert(datetime.parse('9999-12-31T00:00:00Z'):add_calendar({days=1}) == nil)
assert(datetime.parse('0001-01-01T00:00:00Z'):add_calendar({months=-1}) == nil)
for _, bad in ipairs({{days=1.5},{years=math.huge},{months=0/0},{overflow='roll'},{ambiguity='random'}}) do
    assert(jan:add_calendar(bad) == nil)
end
assert(jan:start_of('hour') == nil and jan:start_of('day','random') == nil)
assert(jan:to_rfc3339() == '2024-01-31T12:34:56.123456789+08:00')
print('Calendar months, years, weeks, local days, DST policies and RFC2822 passed')

assert(early:add_calendar({}):timestamp_ns() == early:timestamp_ns())
local fall = assert(datetime.parse('2024-11-02T12:00:00-04:00',nil,'America/New_York'))
assert(fall:add_calendar({days=1}):diff_ms(fall) == 25*3600000)
local skipped = assert(datetime.parse('2011-12-29T12:00:00-10:00',nil,'Pacific/Apia'))
assert(skipped:add_calendar({days=1}) == nil)
